// The page's element ids and the kind of element each is, read from the live markup of web/voice.html,
// and written as a TypeScript type the legacy script's `el` is typed by (`#624 voice-page-modularity`,
// plan step 18: generated ID parity). Comments are not markup; two elements with one id are refused.
//
//   node web/ids.mjs           print the generated module
//   node web/ids.mjs --write   write it to web/src/view/dom/ids.ts
//
// tests/js/page_build.test.mjs holds the written file to what this generates; tests/js/contract.test.mjs
// keeps an independent reading of the markup, so a generator that is wrong is noticed.

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { SHELL, WEB } from "./page_sources.mjs";

/** Where the generated module goes, relative to web/. */
export const IDS_MODULE = "src/view/dom/ids.ts";

/**
 * The DOM type each tag's element has. A tag not here (and an SVG element, which is no HTMLElement) is
 * typed HTMLElement, which every lookup could already assume.
 */
const TYPE_OF_TAG = Object.freeze({
  a: "HTMLAnchorElement",
  button: "HTMLButtonElement",
  details: "HTMLDetailsElement",
  div: "HTMLDivElement",
  form: "HTMLFormElement",
  h1: "HTMLHeadingElement",
  h2: "HTMLHeadingElement",
  h3: "HTMLHeadingElement",
  h4: "HTMLHeadingElement",
  input: "HTMLInputElement",
  label: "HTMLLabelElement",
  li: "HTMLLIElement",
  ol: "HTMLOListElement",
  option: "HTMLOptionElement",
  p: "HTMLParagraphElement",
  pre: "HTMLPreElement",
  select: "HTMLSelectElement",
  span: "HTMLSpanElement",
  textarea: "HTMLTextAreaElement",
  ul: "HTMLUListElement",
});

/** Every id in `html`'s markup with its element's DOM type, in the order they appear. Throws on a repeated id. */
export function elementIds(html) {
  const markup = html.replace(/<!--[\s\S]*?-->/g, " ");
  const found = new Map();
  for (const [, tag, attributes] of markup.matchAll(/<([a-zA-Z][a-zA-Z0-9-]*)\b([^>]*)>/g)) {
    const id = /\sid="([^"]+)"/.exec(attributes);
    if (!id) continue;
    if (found.has(id[1])) throw new Error(`${SHELL} gives two elements the id "${id[1]}"`);
    found.set(id[1], TYPE_OF_TAG[tag.toLowerCase()] || "HTMLElement");
  }
  return found;
}

/** The generated module for `html`. */
export function idsModule(html) {
  const entries = [...elementIds(html)].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = entries.map(([id, type]) => `  ${JSON.stringify(id)}: ${type};`);
  return [
    `// GENERATED by web/ids.mjs from web/${SHELL}; do not edit. \`node web/ids.mjs --write\` writes it again.`,
    "//",
    "// Every element id in the shell's markup, and the kind of element it is: what `el` returns for it.",
    "",
    "/** The shell's element ids, each with its element's DOM type. */",
    "export interface ElementById {",
    ...lines,
    "}",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = idsModule(readFileSync(join(WEB, SHELL), "utf8"));
  if (process.argv.includes("--write")) writeFileSync(join(WEB, IDS_MODULE), text);
  else process.stdout.write(text);
}
